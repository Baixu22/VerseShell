#!/usr/bin/env python3
"""jev_obs_judge: observation-quality judge for VerseShell (task-forest TF-0012).

Answers two narrow questions per failure observation sample:

  diagnostic_sufficient  (Noul)   does the structured observation carry enough
                                  anchor info (path/line/code/expected/found) to
                                  locate and fix the failure?
  script_actionable      (Choice) is the reducer's suggested_next playbook
                                  executable as-is (view -> edit -> rerun)?

Two modes, same report shape:

  heuristic  (default, no API key)  deterministic rules over eval/metrics.json +
                                    the manifest source file. Reproducible offline.
  jev        (TYPESAFE_API_KEY set) the same two questions go to TypeSafe
                                    System One (model "jev-latest"). Judgments
                                    only: this script never generates fix code
                                    and never replaces the regex reducers.

Inputs:  eval/manifest.json (samples + expectations), eval/metrics.json
         (deterministic reducer facts, generated by examples/eval_metrics.rs),
         the sample files themselves (for an observation excerpt).
Outputs: eval/jev_obs_report.json (machine) + eval/jev_obs_report.md (human).
         Every row carries its own source paths and mode/provenance.

Usage:
    python tools/jev_obs_judge.py                    # heuristic, offline
    python tools/jev_obs_judge.py --limit 3          # first N failure samples
    python tools/jev_obs_judge.py --strict           # exit 1 when a row is judged insufficient
    TYPESAFE_API_KEY=... python tools/jev_obs_judge.py --mode jev
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
API_URL = "https://api.typesafe.ai/v1/systemone"
API_MODEL = "jev-latest"
EXCERPT_CHARS = 1200

PATH_LINE_RE = re.compile(r"[\w./\\-]+\.\w{1,6}:\d+")
CODE_RE = re.compile(r"\bE\d{4}\b|\b(?:AssertionError|ModuleNotFoundError|TypeError|ValueError|Error)\b")
DIFF_RE = re.compile(r"assert\s|expected|found|left|right|!=|==", re.IGNORECASE)


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def excerpt(text: str, limit: int = EXCERPT_CHARS) -> str:
    text = text.strip()
    return text if len(text) <= limit else text[:limit] + "\n...[truncated]"


def failure_samples(manifest: dict) -> list[dict]:
    out = []
    for entry in manifest.get("entries", []):
        if entry.get("kind") not in ("reducer_fixture", "adversarial_fixture"):
            continue
        if entry.get("expect", {}).get("success") is not False:
            continue
        out.append(entry)
    return out


def metric_rows(metrics: dict | None) -> dict[str, dict]:
    if not metrics:
        return {}
    rows = metrics.get("reducer_diagnostic_completeness", {}).get("per_entry", [])
    return {r["id"]: r for r in rows}


# ── deterministic judgment ────────────────────────────────────────────────────


def heuristic_judgment(sample: dict, row: dict | None, text: str) -> dict:
    expect = sample.get("expect", {})
    diff_class = bool(expect.get("diff_class"))
    errors = int(row.get("errors", 0)) if row else 0
    complete = int(row.get("expected_found_complete", 0)) if row else 0
    playbook = (row or {}).get("playbook") or {}
    ops = list(playbook.get("suggested_next_ops") or [])

    has_anchor = bool(PATH_LINE_RE.search(text))
    has_code = bool(CODE_RE.search(text))
    has_diff = bool(DIFF_RE.search(text))

    # diagnostic_sufficient: anchor + (diff pair when the class has one) + at
    # least one reducer error survived reduction.
    reasons = []
    score = 0.0
    if errors > 0:
        score += 0.4
        reasons.append(f"reducer kept {errors} error diagnostic(s)")
    else:
        reasons.append("reducer kept no error diagnostic")
    if has_anchor:
        score += 0.3
        reasons.append("raw output carries path:line anchor")
    else:
        reasons.append("no path:line anchor in raw output")
    if diff_class:
        if complete > 0:
            score += 0.3
            reasons.append(f"expected/found extracted ({complete}/{errors})")
        else:
            reasons.append("diff-class failure but no expected/found extracted")
    else:
        if has_diff or has_code:
            score += 0.3
            reasons.append("failure class without expected/found pair (message/code level only)")
        else:
            reasons.append("no code or diff evidence in raw output")
    diagnostic_sufficient = score >= 0.7

    # script_actionable: legal ops, complete arg keys, and a rerun step. When no
    # playbook is emitted, separate "nothing to point at" (by design) from an
    # anchor the reducer failed to structure (a real gap).
    if not ops:
        if has_anchor:
            script_actionable = "unrecoverable_anchor"
            script_reason = "raw output carries a path:line anchor the reducer did not structure"
        else:
            script_actionable = "no_locatable_site"
            script_reason = (
                "no locatable failure site in the observation; "
                "a file-level playbook would be fabricated"
            )
    elif not playbook.get("suggested_next_legal", False):
        script_actionable = "illegal_op"
        script_reason = "playbook contains an op outside the 1.0 ACI allowlist"
    elif not playbook.get("suggested_next_arg_keys_ok", False):
        script_actionable = "missing_params"
        script_reason = "playbook action is missing required argument keys"
    elif not playbook.get("suggested_next_has_rerun", False):
        script_actionable = "no_rerun"
        script_reason = "playbook has no rerun step to confirm the fix"
    else:
        script_actionable = "actionable"
        script_reason = "view -> edit -> rerun with complete argument keys"

    return {
        "diagnostic_sufficient": {
            "value": round(score, 2),
            "answer": diagnostic_sufficient,
            "reasons": reasons,
        },
        "script_actionable": {
            "answer": script_actionable,
            "reasons": [script_reason],
            "by_design": script_actionable == "no_locatable_site",
        },
        "facts": {
            "diff_class": diff_class,
            "errors": errors,
            "expected_found_complete": complete,
            "raw_has_path_line": has_anchor,
            "raw_has_code": has_code,
            "suggested_next_ops": ops,
        },
    }


# ── Jev (TypeSafe System One) judgment ───────────────────────────────────────

QUESTIONS = {
    "diagnostic_sufficient": {
        "type": "noul",
        "instructions": {
            "observation": "`sample.excerpt`",
            "question": (
                "Does this reduced failure observation carry enough structured anchors "
                "(file path, line, error code, and expected/found values when the failure "
                "class has such a pair) for a coding agent to locate and fix the failure "
                "without re-reading the full raw log?"
            ),
        },
        "criteria": {
            "true": "The observation names the failure site and enough detail to act on it",
            "false": "The agent would still need the raw log or a file search to act",
        },
    },
    "script_actionable": {
        "type": "choice",
        "instructions": {
            "observation": "`sample.excerpt`",
            "playbook": "`sample.suggested_next_ops`",
            "question": (
                "Given the observation and the reducer's suggested_next op sequence, "
                "can an agent run this playbook as-is (filling only the sketch values) "
                "to fix and re-verify the failure?"
            ),
        },
        "criteria": {
            "actionable": "view -> edit -> rerun, with a concrete edit target",
            "missing_params": "The playbook lacks a path, edit body, or rerun target",
            "no_script": "The observation provides no repair playbook at all",
            "wrong_target": "The playbook points at a location unrelated to the failure",
        },
    },
}


def jev_judgment(api_key: str, sample: dict, row: dict | None, text: str, timeout: int) -> dict:
    playbook = (row or {}).get("playbook") or {}
    state = {
        "sample": {
            "id": sample.get("id"),
            "profile": sample.get("expect", {}).get("profile"),
            "diff_class": bool(sample.get("expect", {}).get("diff_class")),
            "excerpt": excerpt(text),
            "suggested_next_ops": playbook.get("suggested_next_ops") or [],
        }
    }
    body = json.dumps({"state": state, "model": API_MODEL, "questions": QUESTIONS}).encode("utf-8")
    req = urllib.request.Request(
        API_URL,
        data=body,
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=timeout) as resp:  # noqa: S310 - fixed https endpoint
        payload = json.loads(resp.read().decode("utf-8"))
    answers = payload.get("answers", {})
    diag = answers.get("diagnostic_sufficient", {})
    script = answers.get("script_actionable", {})
    return {
        "diagnostic_sufficient": {
            "value": diag.get("noul"),
            "answer": (diag.get("noul") or 0) >= 0.5,
            "reasons": ["jev noul probability"],
        },
        "script_actionable": {
            "answer": script.get("choice"),
            "reasons": [f"jev choice confidence={script.get('confidence')}"],
            "probabilities": script.get("probabilities"),
        },
        "facts": {"excerpt_chars": len(state["sample"]["excerpt"])},
        "provenance": {"model": payload.get("model"), "usage": payload.get("usage")},
    }


# ── report ───────────────────────────────────────────────────────────────────


def render_markdown(report: dict) -> str:
    lines = [
        "# 观察质检报告（jev_obs_judge）",
        "",
        f"- 生成时间：{report['generated_at']}",
        f"- 判定模式：`{report['mode']}`（judge={report['judge']}）",
        f"- 样本来源：`{report['inputs']['manifest']}`、`{report['inputs']['metrics']}`、`{report['inputs']['bench']}`",
        f"- 样本数：{report['summary']['samples']}；诊断足够：{report['summary']['diagnostic_sufficient']}；"
        f"剧本可执行：{report['summary']['script_actionable']}",
        "- 说明：本脚本只做窄判定（观察是否够修 / 剧本是否可执行），不生成修复代码，不替代正则 reducer。",
        "",
        "| 样本 | profile | 诊断足够 | 剧本判定 | 剧本 op | source |",
        "|------|---------|---------|---------|--------|--------|",
    ]
    for r in report["rows"]:
        ops = " → ".join(r["facts"].get("suggested_next_ops") or []) or "-"
        lines.append(
            f"| {r['id']} | {r['profile']} | {r['diagnostic_sufficient']['answer']}"
            f" | {r['script_actionable']['answer']} | {ops} | `{r['source']}` |"
        )
    lines += ["", "## 逐条理由", ""]
    for r in report["rows"]:
        lines.append(f"### {r['id']} · {r['source']}")
        lines.append(f"- 诊断足够：{r['diagnostic_sufficient']['answer']} "
                     f"(value={r['diagnostic_sufficient']['value']}) — "
                     + "；".join(r["diagnostic_sufficient"]["reasons"]))
        lines.append(f"- 剧本：{r['script_actionable']['answer']} — "
                     + "；".join(r["script_actionable"]["reasons"]))
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--mode", choices=["auto", "heuristic", "jev"], default="auto")
    ap.add_argument("--api-key", default=os.environ.get("TYPESAFE_API_KEY", ""))
    ap.add_argument("--manifest", type=Path, default=ROOT / "eval/manifest.json")
    ap.add_argument("--metrics", type=Path, default=ROOT / "eval/metrics.json")
    ap.add_argument("--report", type=Path, default=ROOT / "eval/jev_obs_report.json")
    ap.add_argument("--markdown", type=Path, default=ROOT / "eval/jev_obs_report.md")
    ap.add_argument("--limit", type=int, default=0, help="judge only the first N failure samples")
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 when any row is judged diagnostic-insufficient")
    args = ap.parse_args(argv)

    mode = args.mode
    if mode == "auto":
        mode = "jev" if args.api_key else "heuristic"
    if mode == "jev" and not args.api_key:
        print("ERROR: --mode jev requires --api-key or TYPESAFE_API_KEY", file=sys.stderr)
        return 2

    if not args.manifest.is_file():
        print(f"ERROR: manifest not found: {args.manifest}", file=sys.stderr)
        return 2
    manifest = load_json(args.manifest)
    metrics = load_json(args.metrics) if args.metrics.is_file() else None
    rows = metric_rows(metrics)

    samples = failure_samples(manifest)
    if args.limit:
        samples = samples[: args.limit]
    if not samples:
        print("ERROR: manifest has no failure samples to judge", file=sys.stderr)
        return 2

    report_rows = []
    for sample in samples:
        sid = sample["id"]
        source = sample["source"]
        src_path = ROOT / source
        text = src_path.read_text(encoding="utf-8", errors="replace") if src_path.is_file() else ""
        try:
            if mode == "jev":
                judgment = jev_judgment(args.api_key, sample, rows.get(sid), text, args.timeout)
            else:
                judgment = heuristic_judgment(sample, rows.get(sid), text)
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, OSError) as e:
            print(f"WARN: jev call failed for {sid} ({e}); falling back to heuristic", file=sys.stderr)
            judgment = heuristic_judgment(sample, rows.get(sid), text)
            judgment.setdefault("provenance", {})["fallback"] = f"jev error: {e}"
        judgment.update({
            "id": sid,
            "profile": sample.get("expect", {}).get("profile"),
            "source": source,
            "source_exists": src_path.is_file(),
            "expect": sample.get("expect", {}),
        })
        report_rows.append(judgment)

    sufficient = sum(1 for r in report_rows if r["diagnostic_sufficient"]["answer"])
    actionable = sum(1 for r in report_rows if r["script_actionable"]["answer"] == "actionable")
    report = {
        "schema": "verseshell.jev-obs-report/v1",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "tools/jev_obs_judge.py",
        "mode": mode,
        "judge": API_MODEL if mode == "jev" else "deterministic-heuristic",
        "inputs": {
            "manifest": str(args.manifest.relative_to(ROOT)),
            "metrics": str(args.metrics.relative_to(ROOT)),
            "metrics_generated_at": (metrics or {}).get("generator"),
            "bench": "bench/aci/results/latest.json",
        },
        "questions": {
            "diagnostic_sufficient": QUESTIONS["diagnostic_sufficient"]["instructions"],
            "script_actionable": QUESTIONS["script_actionable"]["instructions"],
        },
        "summary": {
            "samples": len(report_rows),
            "diagnostic_sufficient": sufficient,
            "diagnostic_sufficient_rate": round(sufficient / len(report_rows), 4),
            "script_actionable": actionable,
            "script_actionable_rate": round(actionable / len(report_rows), 4),
            "script_gaps": sum(
                1 for r in report_rows
                if r["script_actionable"]["answer"] == "unrecoverable_anchor"
            ),
            "script_breakdown": {
                k: sum(1 for r in report_rows if r["script_actionable"]["answer"] == k)
                for k in sorted({r["script_actionable"]["answer"] for r in report_rows})
            },
        },
        "rows": report_rows,
    }

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    args.markdown.write_text(render_markdown(report), encoding="utf-8")

    print(f"jev_obs_judge [{mode}]: {len(report_rows)} samples")
    print(f"  diagnostic_sufficient: {sufficient}/{len(report_rows)}")
    print(f"  script_actionable:     {actionable}/{len(report_rows)} "
          f"({report['summary']['script_breakdown']})")
    print(f"report written: {args.report}")
    print(f"markdown written: {args.markdown}")
    if args.strict and sufficient < len(report_rows):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
